export function resolveResonanceLocalizedMessages(
  candidate: Partial<ResonanceLocalizedMessages> | null | undefined,
): ResonanceLocalizedMessages {
  return Object.freeze({
    ...ENGLISH_RESONANCE_MESSAGES,
    ...nonEmptyMessagesRead(candidate),
  });
}

function nonEmptyMessagesRead(
  candidate: Partial<ResonanceLocalizedMessages> | null | undefined,
): Partial<ResonanceLocalizedMessages> {
  if (!candidate) return {};

  return Object.fromEntries(
    Object.entries(candidate).filter(([, value]) => (
      typeof value === "string" && value.trim().length > 0
    )),
  );
}

const runtimeMessages = (
  globalThis as typeof globalThis & {
    ToneLabResonanceMessages?: Partial<ResonanceLocalizedMessages>;
  }
).ToneLabResonanceMessages;

export const resonanceLocalizedMessages = resolveResonanceLocalizedMessages(
  runtimeMessages,
);
